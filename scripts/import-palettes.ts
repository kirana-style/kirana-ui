/**
 * The colour axes from shadcn/ui: `registry/core/palettes.ts` (every base colour's, theme's and
 * chart colour's values, as `light-dark()` pairs) and `registry/core/colors.ts` (the root's entries
 * that reassign the tokens under each value's attribute on `<html>`), both generated from
 * upstream's `apps/v4/registry/themes.ts`.
 *
 *   bun scripts/import-palettes.ts [<shadcn-ui checkout>]   # default: ../../myna-creative/shadcn-ui
 *
 * Then `vp check --fix` formats them. A value upstream does not have (the codec's `gray`) gets no
 * palette: a design naming it draws the default, and the customizers do not offer it.
 */
import { execFileSync } from "node:child_process"
import { readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const ROOT = join(import.meta.dirname, "..")
const UPSTREAM = process.argv[2] ?? join(ROOT, "../../myna-creative/shadcn-ui")
const THEMES_FILE = join(UPSTREAM, "apps/v4/registry/themes.ts")

type Vars = Record<string, string>
type Theme = { name: string; cssVars: { light: Vars; dark: Vars } }

// The module is one array of data with types around it: the array alone is read.
const text = readFileSync(THEMES_FILE, "utf8")
const end = text.indexOf("] as const")
const source = `return ${text.slice(text.indexOf("["), end + 1)}`
const themes = new Function(source)() as Theme[]
const commit = execFileSync(
  "git",
  ["-C", UPSTREAM, "rev-parse", "--short", "HEAD"],
  {
    encoding: "utf8",
  }
).trim()

/** The base colours upstream's site offers (`apps/v4/registry/base-colors.ts`). */
const BASE = ["neutral", "stone", "zinc", "mauve", "olive", "mist", "taupe"]

const BASE_TOKENS = [
  "background",
  "foreground",
  "card",
  "card-foreground",
  "popover",
  "popover-foreground",
  "muted",
  "muted-foreground",
  "accent",
  "accent-foreground",
  "destructive",
  "border",
  "input",
  "ring",
  "sidebar",
  "sidebar-foreground",
  "sidebar-accent",
  "sidebar-accent-foreground",
  "sidebar-border",
  "sidebar-ring",
]
const THEME_TOKENS = [
  "primary",
  "primary-foreground",
  "secondary",
  "secondary-foreground",
  "sidebar-primary",
  "sidebar-primary-foreground",
]
const CHART_TOKENS = ["chart-1", "chart-2", "chart-3", "chart-4", "chart-5"]

const camel = (name: string) =>
  name.replace(/-([a-z0-9])/g, (_, next: string) => next.toUpperCase())
const pair = (light: string, dark: string) =>
  light === dark ? light : `light-dark(${light}, ${dark})`

function group(names: string[], tokens: string[]) {
  const rows = names.map((name) => {
    const theme = themes.find((entry) => entry.name === name)!
    const values = tokens.map((token) => {
      const light = theme.cssVars.light[token]
      const dark = theme.cssVars.dark[token]
      if (!light || !dark) throw new Error(`${name} has no ${token}`)
      return `    ${camel(token)}: ${JSON.stringify(pair(light, dark))},`
    })
    return `  ${JSON.stringify(name).replace(/^"([a-z]+)"$/, "$1")}: {\n${values.join("\n")}\n  },`
  })
  return `{\n${rows.join("\n")}\n} as const`
}

const all = themes.map((theme) => theme.name)

writeFileSync(
  join(ROOT, "registry/core/palettes.ts"),
  `/**
 * The colours behind the colour axes, each a \`light-dark(<light>, <dark>)\` pair (one value when
 * both modes agree), from shadcn/ui's \`apps/v4/registry/themes.ts\` (MIT) at commit \`${commit}\`.
 * Generated by \`scripts/import-palettes.ts\`; do not edit. The keys are the semantic tokens' names
 * (\`tokens.ts\`): shadcn/ui's custom properties in camel case (\`--card-foreground\` is
 * \`cardForeground\`).
 *
 * shadcn/ui merges a base colour's 32 properties, then the theme's, then the chart colour's
 * \`chart-1\` to \`chart-5\`. The three never set the same token, so each axis owns a disjoint group:
 *
 * - a **base colour** owns the 20 neutral tokens (\`baseColors\`);
 * - a **theme** owns the 6 accent tokens a hue changes (\`themeColors\`); a theme that is a base
 *   colour gives that base colour's own;
 * - a **chart colour** owns the 5 chart tokens (\`chartColors\`).
 *
 * The radius every base colour sets (0.625rem) is the radius axis's default (\`config.ts\`).
 */

export const baseColors = ${group(BASE, BASE_TOKENS)}

export const themeColors = ${group(all, THEME_TOKENS)}

export const chartColors = ${group(all, CHART_TOKENS)}
`
)

/** One token's entries: its value under each axis value but the default, which is the token's own. */
function entries(
  attribute: string,
  names: string[],
  palette: string,
  token: string,
  inner?: (name: string) => string
) {
  return names
    .filter((name) => name !== "neutral")
    .map((name) => {
      const condition = `'[${attribute}="${name}"]'`
      const value = `${palette}.${camel(name)}.${token}`
      return inner
        ? `    [${condition}]: { base: ${value}, ${inner(name)} },`
        : `    [${condition}]: ${value},`
    })
    .join("\n")
}

const BOLD = `'[data-menu-accent="bold"]'`
const blocks: string[] = []
for (const token of BASE_TOKENS.map(camel)) {
  // The menu accent's \`bold\` makes the accent the primary colour, nested under each base colour
  // so it wins there too.
  const accent = token === "accent" || token === "accentForeground"
  const bold = token === "accent" ? "theme.primary" : "theme.primaryForeground"
  blocks.push(
    `  [theme.${token}]: {\n${accent ? `    [${BOLD}]: ${bold},\n` : ""}${entries(
      "data-base-color",
      BASE,
      "baseColors",
      token,
      accent ? () => `[${BOLD}]: ${bold}` : undefined
    )}\n  },`
  )
}
for (const token of THEME_TOKENS.map(camel))
  blocks.push(
    `  [theme.${token}]: {\n${entries("data-theme", all, "themeColors", token)}\n  },`
  )
for (const token of CHART_TOKENS.map(camel))
  blocks.push(
    `  [theme.${token}]: {\n${entries("data-chart-color", all, "chartColors", token)}\n  },`
  )

writeFileSync(
  join(ROOT, "registry/core/colors.ts"),
  `/**
 * The colour axes' entries of the root (\`root.ts\` spreads them): every token a base colour, a
 * theme or a chart colour owns, reassigned under each value's attribute on \`<html>\`. The default
 * value (Neutral) is the token's own (\`tokens.ts\`). Generated by \`scripts/import-palettes.ts\`
 * from \`palettes.ts\`'s values; do not edit.
 */
import { baseColors, chartColors, themeColors } from "./palettes"
import { theme } from "./tokens"

export const colorEntries = {
${blocks.join("\n")}
}
`
)
console.log(
  `palettes: ${BASE.length} base colours, ${all.length} themes and chart colours, from ${commit}`
)
