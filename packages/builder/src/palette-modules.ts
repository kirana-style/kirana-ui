/** The default value: its colours are the tokens' own (`neutral.ts`), so it has no entries. */
const DEFAULT = "neutral"

/** The menu accent's `bold` makes the accent the primary colour, under each base colour too. */
const BOLD = `'[data-menu-accent="bold"]'`
const BOLD_VALUE: Record<string, string> = {
  accent: "theme.primary",
  accentForeground: "theme.primaryForeground",
}

const key = (name: string) =>
  /^[a-z][a-zA-Z0-9]*$/.test(name) ? name : JSON.stringify(name)

/** The values a module keeps: every one, or the one a build is for. */
const kept = (palette: Palette, only?: string) =>
  Object.keys(palette).filter((name) => only === undefined || name === only)

/** What a module holds, for its header: every value, or the project's one. */
const scope = (only?: string) =>
  only === undefined
    ? "every value's"
    : `this project's value only, \`${only}\` (the registry's build for it, which \`ui preset\` replaces)`

function paletteLiteral(palette: Palette, names: readonly string[]) {
  const rows = names.map((name) => {
    const values = Object.entries(palette[name]!).map(
      ([token, value]) => `    ${token}: ${JSON.stringify(value)},`
    )
    return `  ${key(name)}: {\n${values.join("\n")}\n  },`
  })
  return rows.length === 0 ? "{}" : `{\n${rows.join("\n")}\n}`
}

/** An axis's palette module: plain data, importing nothing. */
export function paletteModule(
  spec: ColorAxis,
  palette: Palette,
  commit: string,
  only?: string
): string {
  return `/**
 * The ${spec.axis} axis's colours (\`${spec.attribute}\` on \`<html>\`), ${scope(only)}: each a
 * \`light-dark(<light>, <dark>)\` pair (one value when both modes agree), keyed by the tokens' names
 * (\`tokens.ts\`), shadcn/ui's custom properties in camel case. \`${spec.file}\` puts them on the
 * root. From shadcn/ui's \`apps/v4/registry/themes.ts\` (MIT) at commit \`${commit}\`; generated by
 * \`scripts/import-palettes.ts\`, do not edit.
 */
export const ${spec.palette} = ${paletteLiteral(palette, kept(palette, only))} as const
`
}

/**
 * An axis's entries module: the tokens it owns, reassigned under each value's attribute. `only`
 * names the one value a build keeps.
 */
export function axisModule(
  spec: ColorAxis,
  palette: Palette,
  commit: string,
  only?: string
): string {
  const tokens = Object.keys(palette[DEFAULT] ?? Object.values(palette)[0]!)
  const valued = kept(palette, only).filter((name) => name !== DEFAULT)
  const blocks = tokens.map((token) => {
    const bold = spec.axis === "baseColor" ? BOLD_VALUE[token] : undefined
    const lines = valued.map((name) => {
      const condition = `'[${spec.attribute}="${name}"]'`
      const value = `${spec.palette}.${key(name)}.${token}`
      return bold
        ? `    [${condition}]: { base: ${value}, [${BOLD}]: ${bold} },`
        : `    [${condition}]: ${value},`
    })
    if (bold) lines.unshift(`    [${BOLD}]: ${bold},`)
    return lines.length === 0
      ? ""
      : `  [theme.${token}]: {\n${lines.join("\n")}\n  },`
  })
  const imports =
    valued.length === 0
      ? ""
      : `import { ${spec.palette} } from "./${spec.paletteFile.replace(/\.ts$/, "")}"\n`
  return `/**
 * The ${spec.axis} axis's entries of the root (\`root.ts\` spreads them), ${scope(only)}: the tokens
 * it owns, ${spec.owns}, reassigned under the value's attribute (\`${spec.attribute}\` on
 * \`<html>\`), from \`${spec.paletteFile}\`. The default, Neutral, is the tokens' own
 * (\`neutral.ts\`). From shadcn/ui's palettes at commit \`${commit}\`; generated by
 * \`scripts/import-palettes.ts\`, do not edit.
 */
${imports}${blocks.some(Boolean) ? 'import { theme } from "./tokens"\n\n' : ""}export const ${spec.entries} = {
${blocks.filter(Boolean).join("\n")}
}
`
}

/** The default design's colours, which `tokens.ts` declares the tokens with. */
export function neutralModule(values: Record<string, string>, commit: string) {
  const lines = Object.entries(values).map(
    ([token, value]) => `  ${token}: ${JSON.stringify(value)},`
  )
  return `/**
 * The default design's colours, Neutral's, which \`tokens.ts\` declares the colour tokens with: a base
 * colour's 20 neutral tokens, a theme's 6 accent tokens and a chart colour's 5, each a
 * \`light-dark(<light>, <dark>)\` pair (one value when both modes agree). From shadcn/ui's
 * \`apps/v4/registry/themes.ts\` (MIT) at commit \`${commit}\`; generated, do not edit.
 */
export const neutral = {
${lines.join("\n")}
} as const
`
}

/** A palette module's palette and commit, read back from its text. */
export function readPaletteModule(source: string, spec: ColorAxis) {
  const start = source.indexOf(`export const ${spec.palette} = `)
  const end = source.indexOf(" as const", start)
  if (start < 0 || end < 0)
    throw new Error(`${spec.paletteFile}: no \`${spec.palette}\` to read`)
  const literal = source.slice(
    start + `export const ${spec.palette} = `.length,
    end
  )
  const palette = new Function(`return ${literal}`)() as Palette
  const commit = /at commit `([0-9a-f]+)`/.exec(source)?.[1]
  if (!commit)
    throw new Error(`${spec.paletteFile}: no upstream commit in its header`)
  return { palette, commit }
}
