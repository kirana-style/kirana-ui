/**
 * The colour axes' modules in `registry/core/`, two per axis: its palette as plain data
 * (`base-color-palette.ts`, `theme-palette.ts`, `chart-color-palette.ts`), which the site's pickers
 * and the tests read too, and the root's entries that reassign the tokens it owns under each
 * value's attribute on `<html>` (`base-colors.ts`, `themes.ts`, `chart-colors.ts`), which import
 * it. `scripts/import-palettes.ts` writes them with every value; the builder writes both for one
 * value at a time, the `kirana` item's `flattened.axes`, so a project installs the colours of its
 * own design only (KF-080). One writer for both keeps a value's build the whole module with the
 * other values left out.
 */

/** A palette: each value's colours, keyed by the tokens' names (`cardForeground`). */
export type Palette = Record<string, Record<string, string>>

export type ColorAxis = {
  /** The design's axis, as the `kirana` item's `design.axes` names it. */
  axis: "baseColor" | "theme" | "chartColor"
  /** The palette's module and export, in `registry/core/`. */
  paletteFile: string
  palette: string
  /** The entries' module and export, which `root.ts` spreads. */
  file: string
  entries: string
  attribute: string
  /** What the axis owns, for the modules' headers. */
  owns: string
}

